#!/usr/bin/env python3
"""Convert a Songsterr part JSON into a compact tab-data.js for the sync player.

Usage: make_data.py <part.json> <out.js>
Each measure becomes [length_in_quarters, [[position_in_quarters, [[string, fret], ...]], ...]].
String index 0 is the highest string. Also exports tuning labels and the base tempo.
"""
import json
import sys

NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def convert(src):
    """src is a path to a part JSON, or an already-loaded dict."""
    d = src if isinstance(src, dict) else json.load(open(src))
    sig = [4, 4]
    measures = []
    for i, m in enumerate(d["measures"]):
        sig = m.get("signature", sig)
        length = 4 * sig[0] / sig[1]
        pos = 0.0
        events = []
        for b in (m.get("voices") or [{}])[0].get("beats", []):
            n, den = b["duration"]
            notes = [[x["string"], x["fret"]] for x in b.get("notes", [])
                     if not x.get("rest") and "fret" in x]
            if notes:
                events.append([round(pos, 4), notes])
            pos += 4 * n / den
        if abs(pos - length) > 0.01:
            print(f"warning: measure {i + 1} sums to {pos} quarters, expected {length}")
        measures.append([length, events])
    return {
        "songId": d.get("songId"),
        "bpm": d["automations"]["tempo"][0]["bpm"],
        "strings": [NOTE_NAMES[t % 12] for t in d["tuning"]],
        "measures": measures,
    }


if __name__ == "__main__":
    data = convert(sys.argv[1])
    with open(sys.argv[2], "w") as f:
        f.write("// Generated by make_data.py\nconst TAB = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(len(data["measures"]), "measures,", data["bpm"], "bpm")
