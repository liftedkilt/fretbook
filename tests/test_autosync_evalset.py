"""The real-recording evaluation set: manifest validation, scoring, and the shipped manifest."""

import json
import wave
from pathlib import Path

import numpy as np
import pytest

from fretbook.audio.synth import bar_starts_for, build_document, render
from fretbook.score.evalset import EvalSetError, evaluate_recording, load_manifest

SHIPPED = Path(__file__).parent / "fixtures" / "autosync" / "recordings"


def _write_set(directory: Path, **overrides: object) -> None:
    document = build_document([(4, 4)] * 16, bpm=110)
    starts = bar_starts_for(document, lead_in=1.0)
    audio = render(document, starts)
    with wave.open(str(directory / "take.wav"), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(22050)
        out.writeframes((np.clip(audio, -1, 1) * 32767).astype("<i2").tobytes())
    (directory / "score.tab.json").write_text(json.dumps({"document": document.model_dump()}))
    entry = {
        "id": "take",
        "audio": "take.wav",
        "score": "score.tab.json",
        "title": "Test take",
        "source": "generated by the test",
        "licence": "original",
        "checked_by": "exact, synthetic",
        "bar_starts": starts,
    } | overrides
    (directory / "manifest.json").write_text(json.dumps({"recordings": [entry]}))


def test_shipped_manifest_is_valid_and_every_recording_is_followed() -> None:
    for recording in load_manifest(SHIPPED):
        row = evaluate_recording(recording)
        assert row["median"] < 100, recording.entry.id


def test_missing_manifest_is_an_empty_set(tmp_path: Path) -> None:
    assert load_manifest(tmp_path) == []


def test_a_recording_is_scored_against_its_marks(tmp_path: Path) -> None:
    _write_set(tmp_path)
    (recording,) = load_manifest(tmp_path)
    row = evaluate_recording(recording)
    assert row["name"] == "real: Test take"
    assert row["median"] < 15
    assert row["within50"] == 100


@pytest.mark.parametrize(
    ("override", "message"),
    [
        ({"licence": "all-rights-reserved"}, "licence"),
        ({"bar_starts": [1.0, 0.5, 2.0]}, "increase"),
        ({"bar_starts": [1.0, 2.0]}, "at least"),
        ({"id": "Bad Id"}, "id"),
        ({"audio": "gone.wav"}, "missing"),
        ({"extra": 1}, "extra"),
    ],
)
def test_bad_entries_are_refused(tmp_path: Path, override: dict[str, object], message: str) -> None:
    _write_set(tmp_path, **override)
    with pytest.raises(EvalSetError, match=message):
        load_manifest(tmp_path)


def test_oversized_audio_is_refused(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _write_set(tmp_path)
    monkeypatch.setattr("fretbook.score.evalset.MAX_BYTES", 100)
    with pytest.raises(EvalSetError, match="shorter excerpt"):
        load_manifest(tmp_path)


def test_duplicate_ids_are_refused(tmp_path: Path) -> None:
    _write_set(tmp_path)
    manifest = json.loads((tmp_path / "manifest.json").read_text())
    manifest["recordings"] *= 2
    (tmp_path / "manifest.json").write_text(json.dumps(manifest))
    with pytest.raises(EvalSetError, match="duplicate"):
        load_manifest(tmp_path)
